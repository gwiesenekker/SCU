#!/usr/bin/env python3
"""Generate Windows terminal cell-width intervals from Python's Unicode database."""
from pathlib import Path
import unicodedata as u


def intervals(predicate):
    result = []
    start = end = None
    for code in range(0x110000):
        if predicate(chr(code)):
            if start is None:
                start = code
            end = code
        elif start is not None:
            result.append((start, end))
            start = end = None
    if start is not None:
        result.append((start, end))
    return result


zero = intervals(lambda c: u.category(c) in ('Mn', 'Me', 'Cf') and ord(c) != 0xAD)
wide = intervals(lambda c: u.category(c) != 'Cn' and u.east_asian_width(c) in ('W', 'F'))
text = f'''unit ScuPlatformTerminalWidthWindows;
{{$mode objfpc}}{{$H+}}
interface
function UnicodeCellWidth(Code: Cardinal): Integer;
implementation
// Generated by tools/generate_terminal_width.py; Unicode {u.unidata_version}.
// Width follows assigned East Asian wide/fullwidth characters; combining and
// format marks are zero-width. Ambiguous-width characters occupy one cell.
type TInterval = record First, Last: Cardinal; end;
const
'''
for name, values in [('ZeroWidth', zero), ('DoubleWidth', wide)]:
    text += f'  {name}: array[0..{len(values)-1}] of TInterval = (\n'
    text += ',\n'.join(f'    (First: ${a:X}; Last: ${b:X})' for a, b in values) + ');\n'
text += '''function Contains(const Values: array of TInterval; Code: Cardinal): Boolean;
var Left, Right, Middle: Integer;
begin
  Left := 0; Right := High(Values);
  while Left <= Right do
  begin
    Middle := (Left + Right) div 2;
    if Code < Values[Middle].First then Right := Middle - 1
    else if Code > Values[Middle].Last then Left := Middle + 1
    else Exit(True);
  end;
  Result := False;
end;
function UnicodeCellWidth(Code: Cardinal): Integer;
begin
  if (Code > $10FFFF) or (Code in [$D800..$DFFF]) then Exit(-1);
  if (Code < 32) or ((Code >= $7F) and (Code < $A0)) then Exit(-1);
  if Contains(ZeroWidth, Code) then Exit(0);
  if Contains(DoubleWidth, Code) then Exit(2);
  Result := 1;
end;
end.
'''
# Pascal sets cannot hold Unicode scalar ranges.
text = text.replace('(Code in [$D800..$DFFF])', '((Code >= $D800) and (Code <= $DFFF))')
Path('src/scuplatformterminalwidthwindows.pas').write_text(text)
